package com.example.translatorbot.model;

/**
 * Состояния диалога с пользователем.
 * Определяют, какого действия бот ожидает от пользователя в текущий момент.
 */
public enum UserState {

    /** Пользователь не занят активным диалогом. */
    IDLE,

    /** Бот ожидает выбора исходного языка перевода. */
    WAITING_SOURCE_LANGUAGE,

    /** Бот ожидает выбора целевого языка перевода. */
    WAITING_TARGET_LANGUAGE,

    /** Бот ожидает текст для перевода. */
    WAITING_TEXT
}